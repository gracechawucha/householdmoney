-- 1. rules: account_pattern  '*' = any account (default) | '' = only when
--    there is no account | 'abc' = only when the account is exactly 'abc'
alter table public.rules add column if not exists account_pattern text not null default '*';
alter table public.rules drop constraint if exists rules_direction_match_field_match_type_pattern_key;
create unique index if not exists rules_identity_idx
  on public.rules (direction, match_field, match_type, pattern, account_pattern);

-- the seeded TINGG preset is the airtime till, not the "Facebook Ads" paybill
update public.rules set account_pattern = ''
 where direction = 'out' and match_field = 'name' and match_type = 'equals'
   and pattern = 'TINGG' and account_pattern = '*';

create or replace function public.apply_rules(p_txn uuid default null)
returns integer
language plpgsql
as $$
declare
  n integer;
begin
  with matched as (
    select t.id as txn_id, r.id as rule_id, r.particulars, r.category_id, r.project_id
    from public.transactions t
    cross join lateral (
      select rr.id, rr.particulars, rr.category_id, rr.project_id
      from public.rules rr
      where rr.active
        and rr.direction = t.direction
        and public.rule_subject(t, rr.match_field) is not null
        and (
          (rr.match_type = 'equals'
             and upper(public.rule_subject(t, rr.match_field)) = upper(rr.pattern))
          or
          (rr.match_type = 'contains'
             and position(upper(rr.pattern) in upper(public.rule_subject(t, rr.match_field))) > 0)
        )
        and (
          rr.account_pattern = '*'
          or (rr.account_pattern = '' and coalesce(t.account_ref, '') = '')
          or (rr.account_pattern not in ('*', '')
              and upper(coalesce(t.account_ref, '')) = upper(rr.account_pattern))
        )
      -- most specific wins: account-bound, then exact name, then longer pattern
      order by (rr.account_pattern <> '*') desc, (rr.match_type = 'equals') desc,
               length(rr.pattern) desc, rr.created_at
      limit 1
    ) r
    where t.status = 'unlabeled'
      and (p_txn is null or t.id = p_txn)
  ), upd as (
    update public.transactions t
       set particulars  = m.particulars,
           category_id  = m.category_id,
           project_id   = m.project_id,
           status       = 'labeled',
           label_source = 'rule',
           rule_id      = m.rule_id,
           labeled_at   = now()
      from matched m
     where t.id = m.txn_id
    returning 1
  )
  select count(*) into n from upd;

  return n;
end;
$$;

